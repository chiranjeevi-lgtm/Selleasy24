/**
 * Prepares an isolated environment for the integration tests.
 *
 * Two things matter here:
 *
 *  1. Tests run against their OWN database (`<name>_test`). They truncate every
 *     table between cases, so pointing them at the development database would
 *     silently destroy the demo data on the first run.
 *
 *  2. The test environment gets FRESHLY GENERATED secrets rather than copies of
 *     the development ones. Signing keys and the document encryption key are the
 *     most sensitive values in the project, and there is no reason for a test
 *     process to hold the real ones.
 *
 * Safe to run repeatedly: it will not overwrite an existing .env.test, so a
 * generated encryption key stays stable and previously written test documents
 * remain decryptable across runs.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, '.env');
const TARGET = join(ROOT, '.env.test');

function parseEnv(text) {
  const entries = new Map();
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    entries.set(key, value);
  }
  return entries;
}

/** Appends `_test` to the database name, leaving credentials and host alone. */
export function toTestDatabaseUrl(rawUrl) {
  const url = new URL(rawUrl);
  const name = url.pathname.replace(/^\//, '');
  if (!name) {
    throw new Error('DATABASE_URL has no database name.');
  }
  if (name.endsWith('_test')) {
    return url.toString();
  }
  url.pathname = `/${name}_test`;
  return url.toString();
}

if (!existsSync(SOURCE)) {
  console.error('No .env at the repo root — cannot derive a test environment.');
  process.exit(1);
}

if (existsSync(TARGET)) {
  console.log('.env.test already exists — leaving it untouched.');
  process.exit(0);
}

const source = parseEnv(readFileSync(SOURCE, 'utf8'));

const databaseUrl = source.get('DATABASE_URL');
if (!databaseUrl) {
  console.error('.env has no DATABASE_URL.');
  process.exit(1);
}

// `tr -d` equivalent: the env schema rejects any whitespace in these values,
// and base64 output can wrap on some platforms.
const secret = () => randomBytes(48).toString('base64').replace(/\s/g, '');
const key32 = () => randomBytes(32).toString('base64').replace(/\s/g, '');

const overrides = new Map([
  ['NODE_ENV', 'test'],
  ['DATABASE_URL', toTestDatabaseUrl(databaseUrl)],
  ['JWT_ACCESS_SECRET', secret()],
  ['JWT_REFRESH_SECRET', secret()],
  ['DOCUMENT_ENCRYPTION_KEY', key32()],
  // Nothing should reach a real inbox from a test run.
  ['RESEND_API_KEY', 'test-key-not-used'],
  ['EMAIL_FROM', 'SellEasy24 Test <no-reply@test.invalid>'],
  // A port nothing else binds, so a stray listen cannot collide with the dev API.
  ['API_PORT', '4100'],
]);

const merged = new Map(source);
for (const [key, value] of overrides) {
  merged.set(key, value);
}

const body = [
  '# Generated by scripts/setup-test-env.mjs — do not commit.',
  '#',
  '# Points at a separate database that the test suite truncates freely, and',
  '# carries its own generated secrets so no test process holds the real ones.',
  '',
  ...[...merged].map(([key, value]) => `${key}=${value}`),
  '',
].join('\n');

writeFileSync(TARGET, body);

const shown = new URL(merged.get('DATABASE_URL'));
console.log(`Wrote .env.test — database "${shown.pathname.slice(1)}", fresh secrets generated.`);
